"""Physical-input killswitch for desktop automation.

The guard watches global mouse and keyboard events with ``pynput`` while an
automation action is armed. Synthetic events generated by ``pyautogui`` are
recognised on Windows through the low-level injected flags, so only real user
input aborts. On other platforms a short synthetic-suppression counter is used
as a fallback.

The guard is deliberately independent of the pointer controller: every tool
wraps its action in ``begin_execution`` / ``end_execution`` and calls
``check()`` between movement steps.
"""

from __future__ import annotations

import ctypes
from ctypes import wintypes
import logging
import sys
import threading
import time
from contextlib import contextmanager
from typing import Any

logger = logging.getLogger(__name__)

# Windows low-level hook flag values.
_LLMHF_INJECTED = 0x00000001
_LLKHF_INJECTED = 0x00000010
_LLKHF_LOWER_IL_INJECTED = 0x00000002


class AutomationAbortedException(RuntimeError):
    """Raised when physical user input interrupts an automation action."""

    def __init__(self, reason: str = "Physical input detected.") -> None:
        super().__init__(reason)
        self.reason = reason


class InputFailsafe:
    """Global mouse/keyboard killswitch for one agent process."""

    def __init__(
        self,
        *,
        enabled: bool = True,
        arm_delay_seconds: float = 0.4,
        move_threshold_pixels: int = 4,
    ) -> None:
        self.enabled = bool(enabled)
        self.arm_delay_seconds = max(0.0, float(arm_delay_seconds))
        self.move_threshold_pixels = max(1, int(move_threshold_pixels))

        self._lock = threading.RLock()
        self._mouse_listener: Any | None = None
        self._keyboard_listener: Any | None = None
        self._listeners_started = False
        self._filter_active = False
        self._listener_error: str | None = None

        self._active = False
        self._halted = False
        self._abort_reason = ""
        self._armed_at = 0.0
        self._arm_delay = self.arm_delay_seconds
        self._synthetic_depth = 0
        self._last_physical: tuple[int, int] | None = None
        self._last_event = ""

    # ------------------------------------------------------------- lifecycle
    def start(self) -> None:
        """Start the global listeners (idempotent)."""
        if not self.enabled:
            return

        with self._lock:
            if self._listeners_started:
                return
            self._listeners_started = True

        try:
            from pynput import keyboard, mouse
        except Exception as exc:  # noqa: BLE001 - optional desktop dependency
            with self._lock:
                self._listener_error = f"pynput is unavailable: {exc}"
                self._listeners_started = False
            logger.warning("Input killswitch unavailable: %s", exc)
            return

        try:
            self._mouse_listener = mouse.Listener(
                on_move=self._on_move,
                on_click=self._on_click,
                on_scroll=self._on_scroll,
                win32_event_filter=self._mouse_filter,
            )
            self._keyboard_listener = keyboard.Listener(
                on_press=self._on_press,
                on_release=self._on_release,
                win32_event_filter=self._keyboard_filter,
            )
            self._mouse_listener.daemon = True
            self._keyboard_listener.daemon = True
            self._mouse_listener.start()
            self._keyboard_listener.start()
            self._filter_active = sys.platform == "win32"
        except Exception as exc:  # noqa: BLE001 - desktop session issues
            with self._lock:
                self._listener_error = f"Could not start input listeners: {exc}"
                self._listeners_started = False
            logger.warning("Input killswitch could not start: %s", exc)

    def stop(self) -> None:
        """Stop the listeners. Safe to call repeatedly."""
        with self._lock:
            mouse_listener = self._mouse_listener
            keyboard_listener = self._keyboard_listener
            self._mouse_listener = None
            self._keyboard_listener = None
            self._listeners_started = False
            self._filter_active = False
            self._active = False

        for listener in (mouse_listener, keyboard_listener):
            if listener is None:
                continue
            try:
                listener.stop()
            except Exception:  # noqa: BLE001 - shutdown must not raise
                logger.debug("Stopping an input listener failed", exc_info=True)

    # ------------------------------------------------------------- arming
    def begin_execution(self, *, arm_delay: float | None = None) -> None:
        """Arm the guard for one user-approved UI action."""
        self.start()
        with self._lock:
            if self._halted:
                raise AutomationAbortedException(
                    self._abort_reason
                    or "Automation is halted until the user asks again."
                )
            self._active = True
            self._abort_reason = ""
            self._last_physical = self._cursor_position()
            self._arm_delay = (
                self.arm_delay_seconds
                if arm_delay is None
                else max(0.0, float(arm_delay))
            )
            self._armed_at = time.monotonic()

    def end_execution(self) -> None:
        with self._lock:
            self._active = False

    def check(self) -> None:
        """Raise if a physical input interrupted the current action."""
        with self._lock:
            if self._abort_reason:
                raise AutomationAbortedException(self._abort_reason)

    @contextmanager
    def execution(self, *, arm_delay: float | None = None):
        """Arm, run one action, and always disarm."""
        self.begin_execution(arm_delay=arm_delay)
        try:
            self.check()
            yield self
        finally:
            self.end_execution()

    @contextmanager
    def synthetic(self):
        """Mark events as agent-generated for non-Windows fallback detection."""
        with self._lock:
            self._synthetic_depth += 1
        try:
            yield
        finally:
            with self._lock:
                self._synthetic_depth = max(0, self._synthetic_depth - 1)

    # ------------------------------------------------------------- state
    @property
    def halted(self) -> bool:
        with self._lock:
            return self._halted

    @property
    def abort_reason(self) -> str:
        with self._lock:
            return self._abort_reason

    def reset(self) -> None:
        """Clear a halt at the start of a new user turn."""
        with self._lock:
            self._halted = False
            self._abort_reason = ""
            self._active = False
            self._last_physical = None

    def status(self) -> dict[str, Any]:
        with self._lock:
            return {
                "enabled": self.enabled,
                "listeners_started": self._listeners_started,
                "filter_active": self._filter_active,
                "active": self._active,
                "halted": self._halted,
                "abort_reason": self._abort_reason,
                "listener_error": self._listener_error,
                "last_event": self._last_event,
            }

    # ------------------------------------------------------------- detection
    def _is_armed(self) -> bool:
        with self._lock:
            if not self._active or self._halted:
                return False
            return (time.monotonic() - self._armed_at) >= self._arm_delay

    @staticmethod
    def _cursor_position() -> tuple[int, int] | None:
        try:
            point = wintypes.POINT()
            if ctypes.windll.user32.GetCursorPos(ctypes.byref(point)):
                return int(point.x), int(point.y)
        except Exception:  # noqa: BLE001 - non-Windows or headless session
            return None
        return None

    def _signal(self, reason: str, *, force: bool = False) -> None:
        with self._lock:
            if not self._active and not force:
                return
            if self._halted:
                return
            if not force and (time.monotonic() - self._armed_at) < self._arm_delay:
                return
            self._halted = True
            self._abort_reason = reason
            self._last_event = reason
        logger.warning("Automation aborted: %s", reason)

    def simulate_physical_input(
        self,
        reason: str = "Physical input detected (simulated for test).",
    ) -> None:
        """Test hook: behave exactly like a real physical event."""
        self._signal(reason, force=True)

    @staticmethod
    def _is_injected(data: Any, *, keyboard: bool) -> bool:
        flags = int(getattr(data, "flags", 0) or 0)
        if keyboard:
            return bool(flags & (_LLKHF_INJECTED | _LLKHF_LOWER_IL_INJECTED))
        return bool(flags & _LLMHF_INJECTED)

    def _mouse_filter(self, msg: int, data: Any) -> bool:
        # On Windows this filter sees the injected flag before the callback.
        if self._is_injected(data, keyboard=False):
            return True
        if not self._is_armed():
            return True

        reason: str | None = None
        if msg in (0x0200,):  # WM_MOUSEMOVE
            point = getattr(data, "pt", None)
            if point is not None:
                current = (int(point.x), int(point.y))
                with self._lock:
                    previous = self._last_physical
                    self._last_physical = current
                if previous is None:
                    reason = "Physical mouse movement detected."
                else:
                    delta = abs(current[0] - previous[0]) + abs(current[1] - previous[1])
                    if delta >= self.move_threshold_pixels:
                        reason = "Physical mouse movement detected."
        elif msg in (0x0201, 0x0202, 0x0204, 0x0205, 0x0207, 0x0208, 0x020A):
            # Button down/up, double click, wheel.
            reason = "Physical mouse button or wheel input detected."

        if reason:
            self._signal(reason)
        return True

    def _keyboard_filter(self, msg: int, data: Any) -> bool:
        if self._is_injected(data, keyboard=True):
            return True
        if self._is_armed():
            self._signal("Physical keyboard input detected.")
        return True

    # Fallbacks for non-Windows platforms or if the win32 filter is absent.
    def _on_move(self, x: int, y: int) -> None:
        if self._filter_active or sys.platform == "win32":
            return
        with self._lock:
            if self._synthetic_depth > 0:
                return
        if not self._is_armed():
            return
        with self._lock:
            previous = self._last_physical
            self._last_physical = (int(x), int(y))
        if previous is not None:
            delta = abs(int(x) - previous[0]) + abs(int(y) - previous[1])
            if delta >= self.move_threshold_pixels:
                self._signal("Physical mouse movement detected.")

    def _on_click(self, x: int, y: int, button: Any, pressed: bool) -> None:
        if self._filter_active or sys.platform == "win32":
            return
        with self._lock:
            if self._synthetic_depth > 0:
                return
        if self._is_armed() and pressed:
            self._signal("Physical mouse click detected.")

    def _on_scroll(self, x: int, y: int, dx: int, dy: int) -> None:
        if self._filter_active or sys.platform == "win32":
            return
        with self._lock:
            if self._synthetic_depth > 0:
                return
        if self._is_armed():
            self._signal("Physical mouse wheel input detected.")

    def _on_press(self, key: Any) -> None:
        if self._filter_active or sys.platform == "win32":
            return
        with self._lock:
            if self._synthetic_depth > 0:
                return
        if self._is_armed():
            self._signal("Physical keyboard input detected.")

    def _on_release(self, key: Any) -> None:
        # Key release alone is not a reason to abort; presses are enough.
        return
